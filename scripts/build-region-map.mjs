// Generates src/lib/region-map.ts from a pinned Natural Earth admin-1 GeoJSON (public domain).
// Usage: node scripts/build-region-map.mjs <path-to-ne_10m_admin_1_states_provinces.geojson>
// Download: https://raw.githubusercontent.com/nvkelso/natural-earth-vector/9380cca83db5f9aef52d5e762765100745f84b27/geojson/ne_10m_admin_1_states_provinces.geojson
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const EXPECTED_SHA256 = '22d0e3ad85eb3e27f17cabf8ba2d50e554fbc27a87796ff891d958185da62fb5';
const SLUGS = {
  'SA-01': 'riyadh', 'SA-02': 'makkah', 'SA-03': 'madinah', 'SA-04': 'eastern-province', 'SA-05': 'qassim',
  'SA-06': 'hail', 'SA-07': 'tabuk', 'SA-08': 'northern-borders', 'SA-09': 'jazan', 'SA-10': 'najran',
  'SA-11': 'bahah', 'SA-12': 'jawf', 'SA-14': 'asir',
};
const WIDTH = 600;
const PADDING = 8;
const TOLERANCE = 0.7;
const MIN_RING_AREA = 6;

const input = process.argv[2];
if (!input) throw new Error('Pass the Natural Earth admin-1 GeoJSON path.');
const bytes = readFileSync(input);
const digest = createHash('sha256').update(bytes).digest('hex');
if (digest !== EXPECTED_SHA256) throw new Error(`Unexpected source checksum ${digest}.`);
const features = JSON.parse(bytes.toString('utf8')).features.filter((feature) => feature.properties.adm0_a3 === 'SAU');
if (features.length !== 13 || features.some((feature) => !SLUGS[feature.properties.iso_3166_2])) throw new Error('Expected the thirteen Saudi administrative regions.');

const k = Math.cos((25 * Math.PI) / 180);
const polygons = (geometry) => (geometry.type === 'Polygon' ? [geometry.coordinates] : geometry.coordinates);
const all = features.flatMap((feature) => polygons(feature.geometry).flatMap((polygon) => polygon.flat()));
const minX = Math.min(...all.map(([lon]) => lon * k));
const maxX = Math.max(...all.map(([lon]) => lon * k));
const minY = Math.min(...all.map(([, lat]) => -lat));
const maxY = Math.max(...all.map(([, lat]) => -lat));
const scale = (WIDTH - PADDING * 2) / (maxX - minX);
const height = Math.ceil((maxY - minY) * scale + PADDING * 2);
const project = ([lon, lat]) => [(lon * k - minX) * scale + PADDING, (-lat - minY) * scale + PADDING];

function perpendicular([x, y], [x1, y1], [x2, y2]) {
  const dx = x2 - x1;
  const dy = y2 - y1;
  const length = Math.hypot(dx, dy);
  return length === 0 ? Math.hypot(x - x1, y - y1) : Math.abs(dy * x - dx * y + x2 * y1 - y2 * x1) / length;
}
function simplify(points) {
  if (points.length < 3) return points;
  let index = 0;
  let distance = 0;
  for (let i = 1; i < points.length - 1; i += 1) {
    const d = perpendicular(points[i], points[0], points[points.length - 1]);
    if (d > distance) { index = i; distance = d; }
  }
  if (distance <= TOLERANCE) return [points[0], points[points.length - 1]];
  return [...simplify(points.slice(0, index + 1)).slice(0, -1), ...simplify(points.slice(index))];
}
const area = (ring) => ring.reduce((sum, [x, y], i) => { const [nx, ny] = ring[(i + 1) % ring.length]; return sum + x * ny - nx * y; }, 0) / 2;
function centroid(ring) {
  const a = area(ring);
  let cx = 0;
  let cy = 0;
  ring.forEach(([x, y], i) => { const [nx, ny] = ring[(i + 1) % ring.length]; const f = x * ny - nx * y; cx += (x + nx) * f; cy += (y + ny) * f; });
  return [cx / (6 * a), cy / (6 * a)];
}
const round = (value) => Math.round(value * 10) / 10;

const regions = features.map((feature) => {
  const rings = polygons(feature.geometry).map((polygon) => simplify(polygon[0].map(project)).slice(0, -1));
  const largest = rings.reduce((best, ring) => (Math.abs(area(ring)) > Math.abs(area(best)) ? ring : best));
  const kept = rings.filter((ring) => ring === largest || (ring.length >= 3 && Math.abs(area(ring)) >= MIN_RING_AREA));
  const path = kept.map((ring) => `M${ring.map(([x, y]) => `${round(x)} ${round(y)}`).join('L')}Z`).join('');
  const [x, y] = centroid(largest).map(round);
  return { slug: SLUGS[feature.properties.iso_3166_2], iso: feature.properties.iso_3166_2, path, anchor: [x, y] };
}).sort((a, b) => a.iso.localeCompare(b.iso));

const output = `// Generated by scripts/build-region-map.mjs. Do not edit by hand.
// Made with Natural Earth (public domain): 1:10m Admin 1 States/Provinces, adm0_a3=SAU,
// nvkelso/natural-earth-vector@9380cca83db5f9aef52d5e762765100745f84b27, sha256 ${EXPECTED_SHA256}.
// Equirectangular at 25°N, Douglas-Peucker ${TOLERANCE} units. Generalized, not official or legal boundaries.
export type RegionShape = { slug: string; iso: string; path: string; anchor: readonly [number, number] };
export const REGION_MAP_VIEWBOX = '0 0 ${WIDTH} ${height}';
export const REGION_SHAPES: readonly RegionShape[] = ${JSON.stringify(regions, null, 2)};
`;
writeFileSync(new URL('../src/lib/region-map.ts', import.meta.url), output);
console.log(`Wrote ${regions.length} regions, viewBox 0 0 ${WIDTH} ${height}, ${output.length} bytes.`);
